"""
Graph-grounded analysis for a drug or disease typed by the user.

Everything returned here comes from Neo4j (and the GNN when a trained
checkpoint is loaded). Nothing is generated by a language model.

Pipeline
1. Resolve the free-text name to a real node (Compound or Disease).
2. Candidate generation: partners linked through shared genes
   (drug -> gene -> disease), excluding pairs that are already known treatments.
3. Scoring: GNN score if a trained model is loaded, otherwise a transparent
   graph-evidence score n / (n + 5) where n = number of shared genes.
4. Evidence for the top pair: shared genes, similar compounds, similar
   diseases and pharmacologic class (all queries are specific to the pair).
5. Build the explanation text, reasoning chain and a small subgraph.
"""
import time
from typing import Dict, List, Optional, Tuple

from backend.database import db
from backend.models.gnn import gnn_predictor

KIND_LABEL = {"drug": "Compound", "disease": "Disease"}
LABEL_KIND = {v: k for k, v in KIND_LABEL.items()}

# relation -> (reading forward, reading backward)
VERBS = {
    "BINDS": ("binds", "is bound by"),
    "UPREGULATES": ("upregulates", "is upregulated by"),
    "DOWNREGULATES": ("downregulates", "is downregulated by"),
    "ASSOCIATES": ("is associated with", "is associated with"),
    "TREATS": ("treats", "is treated by"),
    "PALLIATES": ("palliates", "is palliated by"),
    "RESEMBLES": ("resembles", "resembles"),
    "INCLUDES": ("includes", "is a member of"),
    "BELONGS_TO": ("belongs to", "includes"),
    "LOCALIZES": ("localizes to", "hosts"),
    "PARTICIPATES": ("participates in", "involves"),
    "PRESENTS": ("presents", "is a symptom of"),
}

GENE_RELS = "BINDS|UPREGULATES|DOWNREGULATES"
NEIGHBOR_CAPS = {"Gene": 5, "Disease": 4, "Compound": 4}
DEFAULT_CAP = 3
CACHE_TTL = 600
_cache: Dict[Tuple[str, str], Tuple[float, dict]] = {}


def _verb(rel: str, forward: bool) -> str:
    pair = VERBS.get(rel, (rel.lower().replace("_", " "),) * 2)
    return pair[0] if forward else pair[1]


# --------------------------------------------------------------------------
# 1. Entity resolution
# --------------------------------------------------------------------------
def _search(label: str, q: str, limit: int = 5) -> List[dict]:
    rows = db.query(
        f"""
        MATCH (n:{label})
        WHERE n.id = $q OR toLower(n.name) CONTAINS toLower($q)
        RETURN n.id AS id, n.name AS name,
               CASE WHEN n.id = $q OR toLower(n.name) = toLower($q) THEN 0 ELSE 1 END AS rank
        ORDER BY rank, size(n.name)
        LIMIT $limit
        """,
        {"q": q, "limit": limit},
    )
    for r in rows:
        r["kind"] = LABEL_KIND[label]
    return rows


def resolve_entity(q: str, kind: str) -> Tuple[Optional[dict], List[str]]:
    kinds = ["drug", "disease"] if kind == "auto" else [kind]
    found: List[dict] = []
    for k in kinds:
        found.extend(_search(KIND_LABEL[k], q))
    if not found:
        return None, []
    order = {"drug": 0, "disease": 1}
    found.sort(key=lambda r: (r["rank"], order[r["kind"]], len(r["name"])))
    best = found[0]
    suggestions = [r["name"] for r in found[1:5]]
    return {"id": best["id"], "name": best["name"], "kind": best["kind"]}, suggestions


# --------------------------------------------------------------------------
# 2-3. Candidates and scoring
# --------------------------------------------------------------------------
def find_candidates(entity: dict, limit: int = 15) -> List[dict]:
    if entity["kind"] == "drug":
        query = f"""
        MATCH (c:Compound {{id: $id}})-[:{GENE_RELS}]->(g:Gene)-[:ASSOCIATES]->(d:Disease)
        WHERE NOT (c)-[:TREATS|PALLIATES]->(d)
        RETURN d.id AS id, d.name AS name, count(DISTINCT g) AS evidence
        ORDER BY evidence DESC
        LIMIT $limit
        """
    else:
        query = f"""
        MATCH (c:Compound)-[:{GENE_RELS}]->(g:Gene)-[:ASSOCIATES]->(d:Disease {{id: $id}})
        WHERE NOT (c)-[:TREATS|PALLIATES]->(d)
        RETURN c.id AS id, c.name AS name, count(DISTINCT g) AS evidence
        ORDER BY evidence DESC
        LIMIT $limit
        """
    return db.query(query, {"id": entity["id"], "limit": limit})


def _gnn_is_trained() -> bool:
    try:
        return gnn_predictor.get_model_info().get("status") == "loaded"
    except Exception:
        return False


def score_candidates(entity: dict, cands: List[dict]) -> str:
    """Attach a 0-1 score to every candidate. Returns the score source."""
    if _gnn_is_trained():
        if entity["kind"] == "drug":
            pairs = [(entity["id"], c["id"]) for c in cands]
        else:
            pairs = [(c["id"], entity["id"]) for c in cands]
        for c, s in zip(cands, gnn_predictor.predict_batch(pairs)):
            c["score"] = float(s)
        source = "gnn"
    else:
        for c in cands:
            n = c["evidence"]
            c["score"] = n / (n + 5.0)
        source = "graph-evidence"
    cands.sort(key=lambda c: (c["score"], c["evidence"]), reverse=True)
    return source


def get_name(label: str, ident: str) -> Optional[str]:
    """Name of a node by label ('Compound' or 'Disease') and id, or None."""
    if label not in KIND_LABEL.values():
        raise ValueError("unsupported label")
    rows = db.query(f"MATCH (n:{label} {{id: $id}}) RETURN n.name AS name", {"id": ident})
    return rows[0]["name"] if rows else None


# --------------------------------------------------------------------------
# 4. Pair-specific symbolic evidence
# --------------------------------------------------------------------------
def pair_evidence(drug_id: str, disease_id: str) -> dict:
    p = {"cid": drug_id, "did": disease_id}
    genes = db.query(
        f"""
        MATCH (c:Compound {{id: $cid}})-[r:{GENE_RELS}]->(g:Gene)-[:ASSOCIATES]->(d:Disease {{id: $did}})
        RETURN g.id AS id, g.name AS name, type(r) AS rel
        LIMIT 8
        """, p)
    similar_drugs = db.query(
        """
        MATCH (c:Compound {id: $cid})-[:RESEMBLES]-(o:Compound)-[:TREATS]->(d:Disease {id: $did})
        RETURN DISTINCT o.id AS id, o.name AS name
        LIMIT 3
        """, p)
    similar_diseases = db.query(
        """
        MATCH (c:Compound {id: $cid})-[:TREATS]->(o:Disease)-[:RESEMBLES]-(d:Disease {id: $did})
        RETURN DISTINCT o.id AS id, o.name AS name
        LIMIT 3
        """, p)
    classes = db.query(
        """
        MATCH (pc:PharmacologicClass)-[:INCLUDES]->(c:Compound {id: $cid})
        MATCH (pc)-[:INCLUDES]->(o:Compound)-[:TREATS]->(d:Disease {id: $did})
        RETURN DISTINCT pc.id AS pid, pc.name AS pname, o.id AS id, o.name AS name
        LIMIT 3
        """, p)
    return {
        "genes": genes,
        "similar_drugs": similar_drugs,
        "similar_diseases": similar_diseases,
        "classes": classes,
    }


def _coverage(ev: dict) -> float:
    kinds = ["genes", "similar_drugs", "similar_diseases", "classes"]
    return sum(1 for k in kinds if ev[k]) / len(kinds)


def _novelty(ev: dict) -> float:
    """Heuristic: evidence that comes from analogues already used to treat the
    disease (similar compounds / same class / similar disease) means the idea
    is less novel. Purely mechanistic (gene) evidence keeps novelty at 1.0."""
    score = 1.0
    for k in ("similar_drugs", "classes", "similar_diseases"):
        if ev[k]:
            score -= 0.2
    return round(max(score, 0.4), 2)


# --------------------------------------------------------------------------
# 5. Explanation, reasoning chain and subgraph
# --------------------------------------------------------------------------
def _best_path(ev: dict, drug: dict, disease: dict) -> Optional[Tuple[List[dict], List[str]]]:
    """Strongest evidence as a path in drug -> ... -> disease order."""
    if ev["genes"]:
        g = ev["genes"][0]
        return ([drug, {"id": g["id"], "name": g["name"], "label": "Gene"}, disease],
                [g["rel"], "ASSOCIATES"])
    if ev["similar_drugs"]:
        o = ev["similar_drugs"][0]
        return ([drug, {"id": o["id"], "name": o["name"], "label": "Compound"}, disease],
                ["RESEMBLES", "TREATS"])
    if ev["classes"]:
        c = ev["classes"][0]
        return ([drug, {"id": c["pid"], "name": c["pname"], "label": "PharmacologicClass"},
                 {"id": c["id"], "name": c["name"], "label": "Compound"}, disease],
                ["BELONGS_TO", "INCLUDES", "TREATS"])
    if ev["similar_diseases"]:
        o = ev["similar_diseases"][0]
        return ([drug, {"id": o["id"], "name": o["name"], "label": "Disease"}, disease],
                ["TREATS", "RESEMBLES"])
    return None


def _reasoning_chain(path, entity_kind: str) -> List[dict]:
    """UI format: source -(logic)-> step -(logic)-> ... -> target.
    Returns only the intermediate steps, each with the relation leading into it."""
    nodes, rels = path
    if entity_kind == "drug":
        seq_nodes = nodes
        seq_rels = [_verb(r, True) for r in rels]
    else:
        seq_nodes = list(reversed(nodes))
        seq_rels = [_verb(r, False) for r in reversed(rels)]
    return [{"step": seq_nodes[i]["name"], "logic": seq_rels[i - 1]}
            for i in range(1, len(seq_nodes) - 1)]


def _explanation(ev: dict, drug: dict, disease: dict, n_genes: int) -> str:
    d, s = drug["name"], disease["name"]
    parts = []
    if ev["genes"]:
        names = [g["name"] for g in ev["genes"][:3]]
        if n_genes <= 1:
            g = ev["genes"][0]
            parts.append(f"{d} {_verb(g['rel'], True)} {g['name']}, a gene associated with {s}.")
        else:
            listed = ", ".join(names[:-1]) + (" and " if len(names) > 1 else "") + names[-1]
            parts.append(f"{d} acts on {n_genes} genes associated with {s}, including {listed}.")
    if ev["similar_drugs"]:
        o = ev["similar_drugs"][0]["name"]
        parts.append(f"{o} resembles {d} and is a known treatment for {s}.")
    if ev["classes"]:
        c = ev["classes"][0]
        parts.append(f"{d} belongs to {c['pname']}, which includes {c['name']}, a known treatment for {s}.")
    if ev["similar_diseases"]:
        o = ev["similar_diseases"][0]["name"]
        parts.append(f"{d} already treats {o}, which resembles {s}.")
    return " ".join(parts[:3]) or f"No supporting graph paths were found between {d} and {s}."


def _node_key(label: str, ident: str) -> str:
    return f"{label}:{ident}"


def _build_graph(entity: dict, target: dict, drug: dict, disease: dict, ev: dict) -> dict:
    ent_label = KIND_LABEL[entity["kind"]]
    tgt_label = KIND_LABEL[target["kind"]]
    nodes: Dict[str, dict] = {}
    links: List[dict] = []
    seen_links = set()

    def add_node(label: str, ident: str, name: str, val: int):
        key = _node_key(label, ident)
        if key not in nodes:
            nodes[key] = {"id": key, "label": name, "type": label, "val": val}
        else:
            nodes[key]["val"] = max(nodes[key]["val"], val)
        return key

    def add_link(a: str, b: str, rel: str):
        sig = (a, b, rel)
        if a != b and sig not in seen_links:
            seen_links.add(sig)
            links.append({"source": a, "target": b, "relation": _verb(rel, True), "weight": 1})

    drug_label, disease_label = "Compound", "Disease"
    k_drug = add_node(drug_label, drug["id"], drug["name"], 12 if entity["kind"] == "drug" else 10)
    k_dis = add_node(disease_label, disease["id"], disease["name"], 12 if entity["kind"] == "disease" else 10)

    for g in ev["genes"]:
        kg = add_node("Gene", g["id"], g["name"], 7)
        add_link(k_drug, kg, g["rel"])
        add_link(kg, k_dis, "ASSOCIATES")
    for o in ev["similar_drugs"]:
        ko = add_node("Compound", o["id"], o["name"], 7)
        add_link(k_drug, ko, "RESEMBLES")
        add_link(ko, k_dis, "TREATS")
    for o in ev["similar_diseases"]:
        ko = add_node("Disease", o["id"], o["name"], 7)
        add_link(k_drug, ko, "TREATS")
        add_link(ko, k_dis, "RESEMBLES")
    for c in ev["classes"]:
        kp = add_node("PharmacologicClass", c["pid"], c["pname"], 7)
        ko = add_node("Compound", c["id"], c["name"], 6)
        add_link(kp, k_drug, "INCLUDES")
        add_link(kp, ko, "INCLUDES")
        add_link(ko, k_dis, "TREATS")

    # A few real neighbours of the searched entity for context
    rows = db.query(
        f"""
        MATCH (n:{ent_label} {{id: $id}})-[r]-(m)
        RETURN type(r) AS rel, labels(m)[0] AS mtype, m.id AS mid, m.name AS mname,
               (startNode(r) = n) AS outgoing
        LIMIT 80
        """,
        {"id": entity["id"]},
    )
    taken: Dict[str, int] = {}
    center = _node_key(ent_label, entity["id"])
    for r in rows:
        mtype = r["mtype"]
        cap = NEIGHBOR_CAPS.get(mtype, DEFAULT_CAP)
        if taken.get(mtype, 0) >= cap or len(nodes) >= 24:
            continue
        key = add_node(mtype, r["mid"], r["mname"], 5)
        if key == center:
            continue
        taken[mtype] = taken.get(mtype, 0) + 1
        if r["outgoing"]:
            add_link(center, key, r["rel"])
        else:
            add_link(key, center, r["rel"])

    return {"nodes": list(nodes.values()), "links": links}


# --------------------------------------------------------------------------
# Entry point
# --------------------------------------------------------------------------
def analyze_entity(q: str, kind: str = "auto") -> dict:
    q = (q or "").strip()
    if not q:
        return {"status": "error", "message": "Enter a drug or disease name."}

    cache_key = (q.lower(), kind)
    hit = _cache.get(cache_key)
    if hit and time.time() - hit[0] < CACHE_TTL:
        return hit[1]

    entity, suggestions = resolve_entity(q, kind)
    if not entity:
        what = {"drug": "drug", "disease": "disease"}.get(kind, "drug or disease")
        return {"status": "not_found",
                "message": f'No {what} matching "{q}" was found in the knowledge graph.',
                "suggestions": []}

    cands = find_candidates(entity)
    if not cands:
        return {"status": "no_evidence",
                "message": f'"{entity["name"]}" is in the graph, but no gene-based repurposing '
                           f'evidence was found for it.',
                "entity": entity, "suggestions": suggestions}

    score_source = score_candidates(entity, cands)
    top = cands[0]
    other_kind = "disease" if entity["kind"] == "drug" else "drug"
    target = {"id": top["id"], "name": top["name"], "kind": other_kind}
    drug = entity if entity["kind"] == "drug" else target
    disease = entity if entity["kind"] == "disease" else target

    ev = pair_evidence(drug["id"], disease["id"])
    path = _best_path(ev, drug, disease)
    chain = _reasoning_chain(path, entity["kind"]) if path else []

    result = {
        "status": "success",
        "data": {
            "entity": entity,
            "prediction": {
                "source": entity["name"],
                "target": target["name"],
                "targetId": target["id"],
                "neuralScore": round(top["score"], 4),
                "symbolicConfidence": round(_coverage(ev), 2),
                "noveltyScore": _novelty(ev),
                "explanation": _explanation(ev, drug, disease, top["evidence"]),
                "reasoningChain": chain,
                "scoreSource": score_source,
            },
            "alternatives": [
                {"id": c["id"], "name": c["name"], "score": round(c["score"], 4),
                 "sharedGenes": c["evidence"]}
                for c in cands[1:5]
            ],
            "graph": _build_graph(entity, target, drug, disease, ev),
            "suggestions": suggestions,
        },
    }
    _cache[cache_key] = (time.time(), result)
    return result
